export function matchRecipe(
  r: Recipe,
  ingredients: string[],
  machines: string[],
) {
  const missing = r.ingredients.filter((i) => !ingredients.includes(i));
  const hasMachine =
    !r.machines.length || r.machines.some((m) => machines.includes(m));
  return {
    recipe: r,
    missing,
    hasMachine,
    status:
      hasMachine && !missing.length
        ? "pode"
        : hasMachine && missing.length <= 2
          ? "quase"
          : "longe",
  };
}
